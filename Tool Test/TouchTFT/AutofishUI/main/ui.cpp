// วาดหลอดอาหารแบบ Flicker-Free ไม่มีการเคลียร์จอก่อน ทุกพิกเซลระบายรอบเดียว
void ui_draw_food_level(int percent) {
    if (percent < 0) percent = 0;
    if (percent > 100) percent = 100;
    if (percent == s_prevPercent) return;
    s_prevPercent = percent;

    auto& tft = getTft();
    tft.startWrite();

    // วาดหลอดอาหาร: เติมช่องว่างด้านบน และเติมอาหารด้านล่าง
    int fillH = (68 * percent) / 100;
    int emptyH = 68 - fillH;

    if (emptyH > 0) {
        tft.fillRect(19, 186, 25, emptyH, FOOD_BG_COLOR);
    }
    if (fillH > 0) {
        uint16_t fillColor = (percent <= 20) ? TEXT_RED : ((percent <= 50) ? TEXT_YELLOW : TEXT_GREEN);
        tft.fillRect(19, 186 + emptyH, 25, fillH, fillColor);
    }
    tft.drawRect(19, 186, 25, 68, LINE_COLOR);

    // ตัวเลขเปอร์เซ็นต์
    tft.setTextPadding(68);
    tft.setTextColor((percent <= 20) ? TEXT_RED : TEXT_WHITE, PANEL_COLOR);
    tft.setTextSize(2);
    char buf[16];
    snprintf(buf, sizeof(buf), "%d %%", percent);
    tft.drawString(buf, 48, 206);
    tft.setTextPadding(0);

    tft.endWrite();
}

