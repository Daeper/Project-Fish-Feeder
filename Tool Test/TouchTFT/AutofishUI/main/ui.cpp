void ui_draw_header(const char* timeStr, bool wifiConnected) {
    int curWifi = wifiConnected ? 1 : 0;
    bool needUpdateWifi = (curWifi != s_prevWifi);
    bool needUpdateTime = (strcmp(timeStr, s_prevTime) != 0);

    if (!needUpdateWifi && !needUpdateTime) return;

    auto& tft = getTft();
    tft.startWrite();

    if (needUpdateWifi) {
        s_prevWifi = curWifi;
        tft.fillRect(145, 5, 20, 18, BG_COLOR);
        if (wifiConnected) {
            tft.drawBitmap(149, 6, image_Connected_bits, 15, 16, TEXT_GREEN);
        } else {
            tft.drawBitmap(149, 6, image_Disconnected_bits, 15, 16, TEXT_RED);
        }
    }

    if (needUpdateTime) {
        strncpy(s_prevTime, timeStr, sizeof(s_prevTime) - 1);
        tft.setTextPadding(65);
        tft.setTextColor(TEXT_WHITE, BG_COLOR);
        tft.setTextSize(2);
        tft.drawString(timeStr, 174, 6);
        tft.setTextPadding(0);
    }

    tft.endWrite();
}

