void ui_draw_feed_button(bool pressed) {
    int cur = pressed ? 1 : 0;
    if (cur == s_prevBtnPressed) return;
    s_prevBtnPressed = cur;

    auto& tft = getTft();
    tft.startWrite();
    uint16_t btnColor = pressed ? BTN_PRESS_COLOR : BTN_IDLE_COLOR;

    tft.fillCircle(120, 276, 32, btnColor);
    tft.drawCircle(120, 276, 32, TEXT_WHITE);
    tft.drawCircle(120, 276, 33, 0x0000);

    tft.drawBitmap(90, 246, image_btn_icon_bits, 60, 60, TEXT_WHITE);
    tft.endWrite();
}

bool is_touch_feed_btn(uint16_t x, uint16_t y) {
    int dx = (int)x - 120;
    int dy = (int)y - 276;
    return (dx * dx + dy * dy) <= (36 * 36);
}

bool is_touch_toggle1(uint16_t x, uint16_t y) {
    return (x >= 165 && x <= 228 && y >= 85 && y <= 118);
}

bool is_touch_toggle2(uint16_t x, uint16_t y) {
    return (x >= 165 && x <= 228 && y >= 122 && y <= 155);
}
